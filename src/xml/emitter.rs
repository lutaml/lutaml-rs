//! `XmlCodecEmitter` for Rust: namespace-aware readers and writers over the
//! pinned moxml-rs native document faces.
use super::reader_emitter::{emit_reader, plan, refuse};
use super::writer_emitter::emit_writer;
use crate::contracts::*;
use crate::generator::{model_names, RustEmitter};

const HEADER: &str = "// Generated by lutaml-rs. Do not edit.\n\
#![allow(non_snake_case, non_upper_case_globals, non_camel_case_types, clippy::all)]\n\
// The consumer root exposes sibling modules `models`, `contracts` and `xml_rt`\n\
// (= lutaml_rs::xml, with the `xml` feature).\n\
use super::contracts::{ContractResult, ErrorReason};\n\
use super::models::*;\n\
use super::xml_rt::contract::{Projection, XmlReader, XmlWriter};\n\
use super::xml_rt::moxml_binding as rt;\n";

#[derive(Default)]
pub struct RustXmlEmitter;

impl XmlCodecEmitter for RustXmlEmitter {
    fn generate_xml_codecs(
        &self,
        bundle: &Bundle,
        bindings: &TypeBindings,
    ) -> ContractResult<SourceMap> {
        RustEmitter.generate_models(bundle, bindings)?;
        if bindings.values().any(|b| b.codec.is_some()) {
            return Err(refuse(
                "",
                ErrorReason::UnsupportedMapping,
                "",
                "custom codec bindings require a declared callable signature",
            ));
        }
        let names = model_names(bundle)?;
        let mut out = String::from(HEADER);
        for (id, model) in &bundle.models {
            if model.mappings.xml.is_none() {
                continue;
            }
            let plan = plan(bundle, &names, id)?;
            emit_reader(&mut out, &plan);
            emit_writer(&mut out, &plan);
        }
        Ok(SourceMap::from([("xml_codecs.rs".into(), out)]))
    }
}
